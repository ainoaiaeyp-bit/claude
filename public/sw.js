/* Service worker del panel: abre al instante desde la pantalla de inicio. La API nunca se guarda. */
const CACHE = 'panel-v1';
const SHELL = ['/admin.html', '/css/admin.css', '/css/mobile.css', '/favicon.svg', '/icons/icon-192.png'];
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => { e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', (e) => {
  const u = new URL(e.request.url);
  if (e.request.method !== 'GET' || u.origin !== location.origin || u.pathname.startsWith('/api/')) return;
  if (!(u.pathname === '/admin.html' || u.pathname === '/admin' || u.pathname.startsWith('/js/admin/') || u.pathname.startsWith('/css/') || u.pathname.startsWith('/icons/'))) return;
  e.respondWith(caches.open(CACHE).then(async (c) => {
    const hit = await c.match(e.request);
    const net = fetch(e.request).then((r) => { if (r.ok) c.put(e.request, r.clone()); return r; }).catch(() => hit);
    return hit || net;
  }));
});
